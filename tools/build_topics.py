# 과목 판정 게이트 -------------------------------------------------------------
LEGAL_GATE = re.compile(r'『[^』]*법[^』]*』|법\s*제\s*\d|법률|의료법|의료인|면허|진단서|진료기록|보존기간|요양급여|보건복지부장관|시\s*[·.]?\s*도지사|시장[^.]{0,12}군수|연명의료|호스피스|혈액원|헌혈|부적격 혈액|응급의료기관|격리|감염병|검역|질병관리청장|신고하여야|의료기관|휴업|개설|원장|의원|동의서')
PREVENT_GATE = ['직업', '근로', '사업장', '공장', '광부', '산업', '역학', '발생률', '유병률', '치명률', '예방접종', '백신', '암검진', '보건', '집단', '코호트', '바이어스', '민감도', '특이도', '표준화', '건강증진', '금연', '흡연', '비만', '식중독', '대기오염', '중금속', '석면', '진폐', '근로자', '노출', '지역사회', '주민', '보건의료', '정책', '헌장', '일차보건', '건강영향']
CHILD_AGE = re.compile(r'(\d{1,2})\s*(세|개월)\s*(남아|여아|남자아이|여자아이|아이|아동)')
ADULT_AGE = re.compile(r'(\d{2})\s*세\s*(남자|여자|남성|여성)')


def normalize(text):
    return re.sub(r'\s+', ' ', text or '').lower()


def classify(q):
    stem = q.get('stem') or ''
    options = [o.get('text') or '' for o in q.get('options') or []]
    text = normalize(stem + ' ' + ' '.join(options))
    scores = defaultdict(float)
    hits = defaultdict(list)
    for subject, topics in TAXONOMY.items():
        for topic, kws in topics.items():
            for kw in kws:
                k = kw.lower()
                if k in text:
                    scores[(subject, topic)] += 2.0 + min(len(k), 8) * 0.25
                    hits[(subject, topic)].append(kw)

    subj = defaultdict(float)
    for (s, t), v in scores.items():
        subj[s] += v

    if not LEGAL_GATE.search(stem + ' ' + ' '.join(options)):
        subj['의료법규'] = 0
    if not any(k in text for k in PREVENT_GATE):
        subj['예방의학'] = 0
    child = CHILD_AGE.search(stem)
    child_case = bool(child) and not ADULT_AGE.search(stem)

    if not subj:
        return '미분류', '미분류', 0, []
    best_subject = '소아과' if child_case else max(subj.items(), key=lambda kv: kv[1])[0]
    if subj[best_subject] <= 0 and not child_case:
        return '미분류', '미분류', 0, []

    topic_scores = {t: v for (s, t), v in scores.items() if s == best_subject}
    if not topic_scores:
        best_topic = '소아 기타' if best_subject == '소아과' else next(iter(TAXONOMY[best_subject]))
        return best_subject, best_topic, round(subj[best_subject], 2), []
    best_topic = max(topic_scores.items(), key=lambda kv: kv[1])[0]
    return best_subject, best_topic, round(subj[best_subject], 2), hits[(best_subject, best_topic)]


def main():
    index = json.loads((DATA / 'index.json').read_text())
    out = {'version': 1, 'source': 'keyword-v1', 'generated_by': 'tools/build_topics.py', 'map': {}}
    all_counts = Counter()
    topic_counts = Counter()
    weak = []
    samples = defaultdict(list)
    for meta in index['exams']:
        eid = meta['exam_id']
        exam = json.loads((DATA / f'{eid}.json').read_text())
        out['map'][eid] = {}
        for q in exam['questions']:
            s, t, sc, hits = classify(q)
            out['map'][eid][str(q['number'])] = {'s': s, 't': t}
            all_counts[s] += 1
            topic_counts[(s, t)] += 1
            samples[f'{s}/{t}'].append((eid, q['number']))
            if s == '미분류' or sc < 3 or len(hits) < 2:
                weak.append((eid, q['number'], s, t, sc, hits, q['stem'][:70].replace('\n', ' ')))

    (DATA / 'topics.json').write_text(json.dumps(out, ensure_ascii=False, separators=(',', ':')))

    print('과목별 문항 수')
    for s, n in all_counts.most_common():
        print(f'  {s:10s} {n:3d}')
    print(f'  합계 {sum(all_counts.values())}')
    print('\n토픽별 문항 수')
    for (s, t), n in topic_counts.most_common():
        print(f'  {s}/{t}: {n}')
    if '--sample' in sys.argv:
        print('\n토픽별 표본')
        for key, rows in samples.items():
            print(f'  [{key}] ' + ' | '.join(f'{eid[-1]}-{n}' for eid, n in rows[:4]))
    if '--report' in sys.argv:
        print(f'\n검토 필요 {len(weak)}건')
        for row in weak:
            print('  ', row)


if __name__ == '__main__':
    main()
